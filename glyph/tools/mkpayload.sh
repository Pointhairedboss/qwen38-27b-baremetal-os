#!/bin/sh
# mkpayload.sh OUT.asm — embed the examples and the conformance corpus in the
# bare-metal Glyph kernel. Emits NASM with incbin for each program and its
# event script (default "frame\nstate\n", as `glyph test` uses), plus the
# glyph_payloads table read by src/baremetal/glyph_os.c.
set -eu
cd "$(dirname "$0")/.."
OUT=${1:?usage: mkpayload.sh OUT.asm}
ROOT=$PWD
{
    echo "; generated by tools/mkpayload.sh — do not edit"
    echo "bits 64"
    echo "section .rodata"
    echo "global glyph_payloads"
    echo "global glyph_payload_count"
    echo "default_events: db \"frame\", 10, \"state\", 10"
    echo "default_events_end:"
    n=0
    table=""
    for f in examples/*.glyph tests/corpus/*.glyph; do
        base=$(basename "$f" .glyph)
        case "$f" in examples/*) name="examples/$base"; app=1 ;; *) name="corpus/$base"; app=0 ;; esac
        ev="${f%.glyph}.events"
        echo "p${n}_name: db \"$name\", 0"
        echo "p${n}_src: incbin \"$ROOT/$f\""
        echo "p${n}_src_end:"
        if [ -f "$ev" ]; then
            echo "p${n}_ev: incbin \"$ROOT/$ev\""
            echo "p${n}_ev_end:"
            evs="p${n}_ev"; eve="p${n}_ev_end"
        else
            evs="default_events"; eve="default_events_end"
        fi
        table="$table
    dq p${n}_name, p${n}_src, $evs
    dd p${n}_src_end - p${n}_src, $eve - $evs, $app, 0"
        n=$((n + 1))
    done
    echo "align 8"
    echo "glyph_payloads:$table"
    echo "glyph_payload_count: dd $n"
} > "$OUT"
echo "embedded $n programs in $OUT"
