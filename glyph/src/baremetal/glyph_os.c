/* glyph_os.c — a standalone Glyph kernel on the fork's boot path.
 *
 * Linked with the fork's own, unmodified 02-baremetal-os/boot.asm,
 * drivers.asm and runtime.asm and its linker.ld, in the same way Phase 4's
 * bartest.asm supplies its own kernel_main. boot.asm brings the machine to
 * 64-bit long mode (identity-mapped 0-4 GiB, exception IDT, stack aligned)
 * and calls kernel_main below. The Qwen inference kernel is not involved.
 *
 * Multiboot command line:
 *   app=NAME     run examples/NAME.glyph first (default: demo)
 *   glyph=test   run every embedded conformance case, write the transcripts
 *                to COM1 between BEGIN/END markers, then power off
 *
 * Interactive use: ESC leaves an app and shows a menu of the examples;
 * ESC in the menu powers off.
 */
#include "glyph.h"
#include "glyph_backend.h"

/* fork: boot.asm */
extern uint32_t g_mb_magic, g_mb_info;
/* fork: drivers.asm */
extern void serial_init(void);
extern void vga_clear(uint8_t attr);
extern void vga_set_color(uint8_t attr);
extern void console_write(const void *buf, uint64_t len);
extern int  ps2_try_getc(void);
extern int  serial_try_getc(void);
extern void qemu_shutdown(void);
/* glyph_bm.c */
int glyph_bm_run(const char *src, uint64_t len);
int glyph_bm_transcript(const char *src, uint64_t len, const char *script, uint64_t slen);

/* Generated by tools/mkpayload.sh: the examples and the conformance corpus. */
typedef struct glyph_payload {
    const char *name;     /* "examples/demo", "corpus/tc_sieve", ... */
    const char *src;
    const char *events;   /* event script for glyph=test */
    uint32_t    len, elen;
    uint32_t    is_app;   /* listed in the interactive menu */
    uint32_t    pad;
} glyph_payload;
extern const glyph_payload glyph_payloads[];
extern const uint32_t glyph_payload_count;

void kernel_main(void);

/* ---- tiny string helpers (no libc) ---------------------------------------- */
static uint64_t slen(const char *s) { uint64_t n = 0; while (s[n]) n++; return n; }
static void out(const char *s) { console_write(s, slen(s)); }

static void out_u32(uint32_t v)
{
    char b[12];
    int n = 0;
    do { b[n++] = (char)('0' + v % 10); v /= 10; } while (v);
    while (n) console_write(&b[--n], 1);
}

/* Value of key=value in the Multiboot command line, or 0. */
static const char *arg(const char *cmd, const char *key, uint64_t *vlen)
{
    uint64_t k = slen(key);
    while (*cmd) {
        uint64_t i = 0, n = 0;
        while (*cmd == ' ') cmd++;
        while (i < k && cmd[i] == key[i]) i++;
        if (i == k && cmd[k] == '=') {
            const char *v = cmd + k + 1;
            while (v[n] && v[n] != ' ') n++;
            *vlen = n;
            return v;
        }
        while (*cmd && *cmd != ' ') cmd++;
    }
    return 0;
}

static int eq_n(const char *a, uint64_t n, const char *b)
{
    uint64_t i;
    for (i = 0; i < n; i++) if (a[i] != b[i]) return 0;
    return b[n] == 0;
}

static const char *cmdline(void)
{
    const uint32_t *mbi = (const uint32_t *)(uintptr_t)g_mb_info;
    if (g_mb_magic != 0x2BADB002u || !mbi || !(mbi[0] & 4u)) return "";
    return (const char *)(uintptr_t)mbi[4];             /* MBI_CMDLINE, offset 16 */
}

/* ---- modes ------------------------------------------------------------------ */
static void conformance(void)
{
    uint32_t i;
    for (i = 0; i < glyph_payload_count; i++) {
        const glyph_payload *p = &glyph_payloads[i];
        out("=== GLYPH BEGIN ");
        out(p->name);
        out(" ===\n");
        glyph_bm_transcript(p->src, p->len, p->events, p->elen);
        out("=== GLYPH END ");
        out(p->name);
        out(" ===\n");
    }
    out("=== GLYPH DONE ");
    out_u32(glyph_payload_count);
    out(" ===\n");
}

static int key_wait(void)
{
    for (;;) {
        int c = serial_try_getc();
        if (c < 0) c = ps2_try_getc();
        if (c >= 0) return c;
        __asm__ volatile("pause");
    }
}

/* Index of the n-th app, or -1. */
static int nth_app(uint32_t n)
{
    uint32_t i, seen = 0;
    for (i = 0; i < glyph_payload_count; i++)
        if (glyph_payloads[i].is_app && seen++ == n) return (int)i;
    return -1;
}

static int menu(void)
{
    uint32_t n;
    int i;
    vga_clear(0x07);
    vga_set_color(0x0B);
    out("Glyph " GLYPH_VERSION " on bare metal (qwen38-27b-baremetal-os boot path)\n\n");
    vga_set_color(0x07);
    for (n = 0; (i = nth_app(n)) >= 0 && n < 9; n++) {
        char key[4] = { ' ', (char)('1' + n), ' ', 0 };
        out(key);
        out(glyph_payloads[i].name + 9);            /* skip "examples/" */
        out("\n");
    }
    vga_set_color(0x0E);
    out("\nPress 1-");
    out_u32(n);
    out(" to run a program, ESC to power off.\n");
    vga_set_color(0x07);
    for (;;) {
        int c = key_wait();
        if (c == 27) return -1;
        if (c >= '1' && c < '1' + (int)n) return nth_app((uint32_t)(c - '1'));
    }
}

void kernel_main(void)
{
    const char *cmd;
    const char *v;
    uint64_t vlen = 0;
    int app = -1;
    uint32_t i;

    serial_init();
    vga_clear(0x07);
    cmd = cmdline();
    out("[glyph-os] Glyph " GLYPH_VERSION ", cmdline: ");
    out(cmd);
    out("\n");

    v = arg(cmd, "glyph", &vlen);
    if (v && eq_n(v, vlen, "test")) {
        conformance();
        qemu_shutdown();
    }
    v = arg(cmd, "app", &vlen);
    for (i = 0; i < glyph_payload_count; i++) {
        const glyph_payload *p = &glyph_payloads[i];
        if (p->is_app && eq_n(v ? v : "demo", v ? vlen : 4, p->name + 9)) app = (int)i;
    }
    for (;;) {
        if (app >= 0) glyph_bm_run(glyph_payloads[app].src, glyph_payloads[app].len);
        app = menu();
        if (app < 0) {
            vga_clear(0x07);
            out("[glyph-os] powering off\n");
            qemu_shutdown();
        }
    }
}
